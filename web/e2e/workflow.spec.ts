test('real isolated rebuild rejects stale export and refreshed result exports new revision',async({page})=>{
 const workspace=process.env.AGENTATLAS_R1_BROWSER_WORKSPACE;
 test.skip(!workspace,'Requires explicit isolated workspace; never mutates formal cards');
 const root=resolve(workspace!);
 expect(root.replaceAll('\\','/')).toContain('/.local/fix-r1/browser-workspace');
 const source=resolve(root,'content/cases/stable-idempotency.md');
 const original=readFileSync(source,'utf8');
 const rebuild=()=>execFileSync(process.env.AGENTATLAS_R1_PYTHON!,['-m','backend','rebuild'],{cwd:root});
 await page.goto('/');
 await page.getByLabel('要求人工审批').selectOption('yes');
 await page.getByLabel('外部工具幂等能力').selectOption('yes');
 await page.getByRole('combobox',{name:'问题簇',exact:true}).selectOption('recovery');
 await page.getByRole('button',{name:'检索并检查约束 →'}).click();
 await expect(page.getByTestId('stable-idempotency')).toBeVisible();
 const decisionRevision=await page.locator('.candidates > .hint').textContent();
 const downloads:string[]=[];page.on('download',d=>downloads.push(d.suggestedFilename()));
 try{
  writeFileSync(source,original+'\n\nR1 isolated revision change.\n');rebuild();
  const conflict=page.waitForResponse(r=>r.url().endsWith('/api/export'));
  await page.getByRole('button',{name:'导出 JSON ↓'}).click();
  expect((await conflict).status()).toBe(409);
  await expect(page.getByRole('alert')).toContainText('重新查询');
  expect(downloads).toEqual([]);
  const mdConflict=page.waitForResponse(r=>r.url().endsWith('/api/export'));
  await page.getByRole('button',{name:'导出 Markdown ↓'}).click();
  expect((await mdConflict).status()).toBe(409);expect(downloads).toEqual([]);
  await page.getByRole('button',{name:'检索并检查约束 →'}).click();
  await expect(page.locator('.candidates > .hint')).not.toHaveText(decisionRevision!);
  const downloaded=page.waitForEvent('download');await page.getByRole('button',{name:'导出 JSON ↓'}).click();
  const file=await downloaded;const stream=await file.createReadStream();const chunks:Buffer[]=[];for await(const chunk of stream!)chunks.push(chunk);
  const report=JSON.parse(Buffer.concat(chunks).toString());expect(await page.locator('.candidates > .hint').textContent()).toContain(report.content_revision);
  expect(report.comparison.find((c:any)=>c.card.id==='stable-idempotency').card.body).toContain('R1 isolated revision change.');
 }finally{writeFileSync(source,original);rebuild();}
});

